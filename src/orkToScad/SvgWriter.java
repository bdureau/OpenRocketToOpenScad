package orkToScad;

import java.awt.geom.Area;
import java.awt.geom.PathIterator;
import java.awt.geom.Rectangle2D;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.text.DecimalFormat;
import java.text.DecimalFormatSymbols;
import java.util.Locale;

/**
 * Writes cut outlines as SVG files for laser cutters and CNC routers.
 *
 * The page is sized in millimetres ({@code width="..mm"}) with a viewBox in millimetres, so the part
 * imports at its real size. Outlines are red hairlines (0.1 mm) without fill, as most laser
 * software expects for cut lines. The part name is stored in the SVG title only (no visible text,
 * so nothing gets engraved by mistake).
 */
public final class SvgWriter {

    private static final double MARGIN = 2.0; // mm around the part
    private static final String STYLE = "fill=\"none\" stroke=\"#ff0000\" stroke-width=\"0.1\"";

    private SvgWriter() {
    }

    /** Writes the outline(s) of an area (y up in the area, converted to SVG's y down). */
    public static void writeOutline(Path file, String title, Area area) throws IOException {
        Rectangle2D b = area.getBounds2D();
        StringBuilder d = new StringBuilder();
        double[] c = new double[6];
        for (PathIterator it = area.getPathIterator(null, 0.005); !it.isDone(); it.next()) {
            switch (it.currentSegment(c)) {
                case PathIterator.SEG_MOVETO:
                    d.append('M').append(n(c[0])).append(',').append(n(-c[1])).append(' ');
                    break;
                case PathIterator.SEG_LINETO:
                    d.append('L').append(n(c[0])).append(',').append(n(-c[1])).append(' ');
                    break;
                case PathIterator.SEG_CLOSE:
                    d.append("Z ");
                    break;
                default:
                    break;
            }
        }
        String body = "  <path d=\"" + d.toString().trim() + "\" " + STYLE + "/>\n";
        write(file, title, b.getMinX(), -b.getMaxY(), b.getWidth(), b.getHeight(), body);
    }

    /** Writes concentric circles (rings, bulkheads); radii of 0 are skipped. */
    public static void writeCircles(Path file, String title, double... radii) throws IOException {
        double max = 0;
        StringBuilder body = new StringBuilder();
        for (double r : radii) {
            max = Math.max(max, r);
            if (r > 0) {
                body.append("  <circle cx=\"0\" cy=\"0\" r=\"").append(n(r)).append("\" ").append(STYLE).append("/>\n");
            }
        }
        write(file, title, -max, -max, 2 * max, 2 * max, body.toString());
    }

    private static void write(Path file, String title, double x, double y, double w, double h, String body)
            throws IOException {
        double vx = x - MARGIN, vy = y - MARGIN, vw = w + 2 * MARGIN, vh = h + 2 * MARGIN;
        String svg = "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n"
                + "<svg xmlns=\"http://www.w3.org/2000/svg\" version=\"1.1\" width=\"" + n(vw) + "mm\" height=\""
                + n(vh) + "mm\" viewBox=\"" + n(vx) + " " + n(vy) + " " + n(vw) + " " + n(vh) + "\">\n"
                + "  <title>" + escape(title) + "</title>\n"
                + "  <desc>Generated by ORKtoSCAD. Units: mm. Red lines are cut lines.</desc>\n"
                + body
                + "</svg>\n";
        Files.writeString(file, svg, StandardCharsets.UTF_8);
    }

    private static String n(double v) {
        String s = new DecimalFormat("0.####", DecimalFormatSymbols.getInstance(Locale.ROOT)).format(v);
        return s.equals("-0") ? "0" : s;
    }

    private static String escape(String s) {
        return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("\"", "&quot;");
    }
}
